#!/usr/bin/env node
/**
 * Extracts every ```mermaid``` code block from each markdown file under docs/
 * and renders it to an SVG in docs/diagrams/.
 *
 * Filenames follow the pattern:   <doc-slug>-NN-<heading-slug>.svg
 * where NN is the 1-based diagram index within the file and heading-slug
 * is derived from the closest preceding section heading.
 *
 * Usage:
 *   npm run docs:render
 */
import { readFile, writeFile, mkdir, readdir, rm } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join, basename, extname } from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const projectRoot = join(__dirname, "..");
const docsDir = join(projectRoot, "docs");
const diagramsDir = join(docsDir, "diagrams");
const tmpDir = join(diagramsDir, ".tmp");

function slugify(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}

function extractBlocks(markdown) {
  const lines = markdown.split("\n");
  const blocks = [];
  let currentHeading = null;
  let inBlock = false;
  let blockStart = -1;
  let blockLines = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const headingMatch = /^#{1,6}\s+(.+?)\s*$/.exec(line);
    if (headingMatch && !inBlock) {
      currentHeading = headingMatch[1].replace(/^[\d.\s]+/, "").trim();
      continue;
    }
    if (!inBlock && /^```mermaid\s*$/.test(line)) {
      inBlock = true;
      blockStart = i + 1;
      blockLines = [];
      continue;
    }
    if (inBlock && /^```\s*$/.test(line)) {
      blocks.push({
        heading: currentHeading || "diagram",
        startLine: blockStart,
        content: blockLines.join("\n"),
      });
      inBlock = false;
      continue;
    }
    if (inBlock) {
      blockLines.push(line);
    }
  }
  return blocks;
}

function runMmdc(input, output) {
  return new Promise((resolve, reject) => {
    const mmdcBin = join(
      projectRoot,
      "node_modules",
      ".bin",
      process.platform === "win32" ? "mmdc.cmd" : "mmdc"
    );
    const args = [
      "-i",
      input,
      "-o",
      output,
      "-b",
      "transparent",
      "-t",
      "default",
    ];
    const child = spawn(mmdcBin, args, { stdio: "pipe" });
    let stderr = "";
    child.stderr.on("data", (d) => (stderr += d.toString()));
    child.on("error", reject);
    child.on("exit", (code) => {
      if (code === 0) resolve();
      else reject(new Error(`mmdc exited ${code}\n${stderr}`));
    });
  });
}

async function main() {
  if (!existsSync(diagramsDir)) {
    await mkdir(diagramsDir, { recursive: true });
  }
  if (!existsSync(tmpDir)) {
    await mkdir(tmpDir, { recursive: true });
  }

  const entries = await readdir(docsDir);
  const mdFiles = entries
    .filter((f) => f.endsWith(".md"))
    .map((f) => join(docsDir, f));

  const manifest = [];
  let totalRendered = 0;

  for (const mdPath of mdFiles) {
    const docSlug = slugify(basename(mdPath, extname(mdPath)));
    const md = await readFile(mdPath, "utf8");
    const blocks = extractBlocks(md);

    if (blocks.length === 0) {
      console.log(`  ${basename(mdPath)}: no mermaid blocks`);
      continue;
    }

    console.log(`\n${basename(mdPath)}: ${blocks.length} diagram(s)`);

    for (let idx = 0; idx < blocks.length; idx++) {
      const block = blocks[idx];
      const seq = String(idx + 1).padStart(2, "0");
      const headingSlug = slugify(block.heading) || "diagram";
      const baseName = `${docSlug}-${seq}-${headingSlug}`;
      const mmdPath = join(tmpDir, `${baseName}.mmd`);
      const svgPath = join(diagramsDir, `${baseName}.svg`);

      await writeFile(mmdPath, block.content + "\n");
      try {
        await runMmdc(mmdPath, svgPath);
        console.log(`  -> ${baseName}.svg`);
        manifest.push({
          source: basename(mdPath),
          heading: block.heading,
          sourceLine: block.startLine,
          file: `diagrams/${baseName}.svg`,
        });
        totalRendered++;
      } catch (e) {
        console.error(`  FAILED ${baseName}: ${e.message}`);
      }
    }
  }

  // Write a manifest so we can see what was rendered.
  const manifestPath = join(diagramsDir, "INDEX.md");
  const lines = [
    "# Diagram index",
    "",
    "Auto-generated by `scripts/render-diagrams.mjs`. Do not edit by hand.",
    "",
    "Regenerate with `npm run docs:render`.",
    "",
    "| Source | Section | SVG |",
    "|---|---|---|",
    ...manifest.map(
      (m) => `| ${m.source} (line ${m.sourceLine}) | ${m.heading} | [${basename(m.file)}](${basename(m.file)}) |`
    ),
    "",
  ];
  await writeFile(manifestPath, lines.join("\n"));

  // Clean up the temp workdir
  await rm(tmpDir, { recursive: true, force: true });

  console.log(`\nRendered ${totalRendered} diagram(s) -> docs/diagrams/`);
  console.log(`Manifest: docs/diagrams/INDEX.md`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
